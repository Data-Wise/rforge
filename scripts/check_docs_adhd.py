#!/usr/bin/env python3
"""Advisory ADHD-friendliness report for the rforge docs pages.

Read-only and stdlib-only. Not wired into any gate: findings never change the
exit code (0), so the report is a to-do list, not a verdict. Exit 2 only means
that no .md files were found for the given paths. See docs/reference/adhd-design-system.md.

Per page it reports:

* TL;DR      an admonition (or blockquote) titled "TL;DR"
* time       a time line near the top ("⏱️ 10 minutes", or "N minutes")
* longest    the longest paragraph, in sentences (flagged above --max-sentences)
* next       a next-step block (an ``adhd-next`` admonition, or a heading or
             admonition title that starts with "Next")

Usage:
    python3 scripts/check_docs_adhd.py                 # every page under docs/
    python3 scripts/check_docs_adhd.py docs/guides     # a folder or single files
    python3 scripts/check_docs_adhd.py --summary-only
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_ROOT = REPO_ROOT / "docs"
GENERATED_MARKER = "Auto-generated by"
TIME_WINDOW = 1200  # characters from the top of the page searched for a time line

FENCE_RE = re.compile(r"^\s*(```+|~~~+)")
TLDR_RE = re.compile(r"^\s*(!{3}|\?{3}\+?)\s+\w+[^\n]*TL;DR|^\s*>\s*\*\*TL;DR", re.I | re.M)
TIME_RE = re.compile(r"⏱|\b\d+\s*(?:-\s*\d+\s*)?(?:minutes?|mins?)\b", re.I)
NEXT_ADMON_RE = re.compile(r"^\s*(?:!{3}|\?{3}\+?)\s+[^\n]*\badhd-next\b", re.M)
# "Next", "Next step(s)", "Next up", "What's next", optionally followed by a colon or the closing quote.
NEXT_WORD = r"(?:what['’]s[ \t]+)?next(?:[ \t]+steps?|[ \t]+up)?(?=[ \t]*(?:[:\"'’]|$))"
NEXT_TITLE_RE = re.compile(
    rf"^[ \t]*(?:\#{{1,6}}[ \t]+\W*{NEXT_WORD}"  # heading: "## Next steps", "## 👉 Next"
    rf"|(?:!{{3}}|\?{{3}}\+?)[ \t]+[^\n\"']*[\"']\W*{NEXT_WORD})",  # title: !!! success "Next step"
    re.I | re.M,
)
ABBREV_RE = re.compile(r"\b(?:e\.g|i\.e|vs|etc|cf|approx|no)\.", re.I)
SENTENCE_END_RE = re.compile(r"[.!?]+(?=\s|$)")


@dataclass
class PageReport:
    path: Path
    generated: bool
    has_tldr: bool
    has_time: bool
    longest: int
    has_next: bool


def strip_front_matter(text: str) -> str:
    if text.startswith("---\n"):
        end = text.find("\n---", 4)
        if end != -1:
            return text[end + 4 :]
    return text


LIST_ITEM_RE = re.compile(r"(?:[-*+]|\d+[.)])\s")
BLOCK_OPEN_RE = re.compile(r"(?:!{3}|\?{3}\+?|===\+?)\s")


def prose_paragraphs(text: str) -> list[str]:
    """Return running-text paragraphs, skipping code, tables, lists and headings.

    Content indented under an admonition (``!!!``/``???``) or a content tab
    (``===``) is prose and is measured. Other 4-space-indented lines are code or
    list continuations and are skipped.
    """
    paragraphs: list[str] = []
    current: list[str] = []
    in_fence = False
    in_block = False  # inside an indented admonition or tab body

    def flush() -> None:
        if current:
            paragraphs.append(" ".join(current))
            current.clear()

    for raw in text.splitlines():
        if FENCE_RE.match(raw):
            flush()
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        line = raw.strip()
        if not line:
            flush()
            continue
        if not raw.startswith(("    ", "\t")):
            in_block = bool(BLOCK_OPEN_RE.match(raw))
        elif not in_block:
            flush()  # indented code or list continuation
            continue
        # Non-prose lines: headings, tables, list items, HTML tags, attr_list
        # lines, blockquotes, admonition/tab openers.
        if line.startswith(("#", "|", "<", "{", ">")) or LIST_ITEM_RE.match(line) or BLOCK_OPEN_RE.match(line):
            flush()
            continue
        current.append(line)
    flush()
    return paragraphs


def count_sentences(paragraph: str) -> int:
    clean = re.sub(r"`[^`]*`", "X", paragraph)  # inline code never ends a sentence
    clean = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", clean)  # link text only
    clean = ABBREV_RE.sub("abbr", clean)
    return len(SENTENCE_END_RE.findall(clean)) or 1


def analyze(path: Path) -> PageReport:
    text = path.read_text(encoding="utf-8", errors="replace")
    body = strip_front_matter(text)
    counts = [count_sentences(p) for p in prose_paragraphs(body)]
    return PageReport(
        path=path,
        generated=GENERATED_MARKER in text[:400],
        has_tldr=bool(TLDR_RE.search(body)),
        has_time=bool(TIME_RE.search(body[:TIME_WINDOW])),
        longest=max(counts, default=0),
        has_next=bool(NEXT_ADMON_RE.search(body) or NEXT_TITLE_RE.search(body)),
    )


def collect(paths: list[str]) -> list[Path]:
    files: list[Path] = []
    for entry in paths:
        p = Path(entry)
        if p.is_dir():
            files.extend(sorted(p.rglob("*.md")))
        elif p.suffix == ".md" and p.exists():
            files.append(p)
        else:
            print(f"skip (not a .md file or folder): {entry}", file=sys.stderr)
    # The docs-root README is the GitHub-facing folder readme, excluded by mkdocs.
    return [f for f in files if not (f.name == "README.md" and f.parent.resolve() == DEFAULT_ROOT)]


def rel(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def mark(flag: bool) -> str:
    return "yes" if flag else "-"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("paths", nargs="*", default=[str(DEFAULT_ROOT)], help="folders or .md files (default: <repo>/docs)")
    ap.add_argument("--max-sentences", type=int, default=5, help="paragraph length that counts as dense (default 5)")
    ap.add_argument("--summary-only", action="store_true", help="print only the summary")
    args = ap.parse_args(argv)

    files = collect(args.paths)
    if not files:
        print("error: no .md files found for the given paths", file=sys.stderr)
        return 2
    reports = [analyze(f) for f in files]
    authored = [r for r in reports if not r.generated]
    generated = [r for r in reports if r.generated]

    if not args.summary_only:
        width = max((len(rel(r.path)) for r in authored), default=10)
        print(f"{'page'.ljust(width)}  TL;DR  time  longest  next")
        for r in authored:
            dense = " (dense)" if r.longest > args.max_sentences else ""
            print(
                f"{rel(r.path).ljust(width)}{mark(r.has_tldr):<5}  {mark(r.has_time):<4}  "
                f"{r.longest:>7}  {mark(r.has_next):<4}{dense}"
            )
        print()

    n = len(authored)

    def pct(k: int) -> str:
        return f"{k}/{n} ({100 * k // n}%)" if n else "0/0"

    dense_pages = sum(1 for r in authored if r.longest > args.max_sentences)
    print(f"Summary: {n} authored pages, {len(generated)} generated pages skipped")
    print(f"  TL;DR box:        {pct(sum(r.has_tldr for r in authored))}")
    print(f"  time line:        {pct(sum(r.has_time for r in authored))}")
    print(f"  next-step block:  {pct(sum(r.has_next for r in authored))}")
    print(f"  dense paragraph:  {dense_pages}/{n} pages have one over {args.max_sentences} sentences")
    print("Advisory only: findings never fail the build.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
